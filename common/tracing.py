"""End-to-end tracing (E3).

One trace id is created at the UI request (X-Trace-Id header, or generated by the API),
stored on the run, passed to the graph via config, attached to every node span, every
LLM call (tokens + cost per node) and every MCP tool call, and written into the
marketplace server's audit log.  Spans are stored in the app DB (spans table) and, if
PHOENIX_COLLECTOR_ENDPOINT / OTEL_EXPORTER_OTLP_ENDPOINT is set, exported to Arize
Phoenix via OpenTelemetry so the "full trace" link opens in Phoenix.
All attributes are PII-masked before they are stored or exported.
"""
from __future__ import annotations

import contextvars
import json
import os
import time
import uuid
from contextlib import contextmanager
from functools import lru_cache

from agent.guards import mask_obj

current_trace: contextvars.ContextVar[str | None] = contextvars.ContextVar("trace_id", default=None)
current_span: contextvars.ContextVar[str | None] = contextvars.ContextVar("span_id", default=None)
current_thread: contextvars.ContextVar[str | None] = contextvars.ContextVar("thread_id", default=None)
current_user: contextvars.ContextVar[str | None] = contextvars.ContextVar("user_id", default=None)


def new_trace_id() -> str:
    return uuid.uuid4().hex


@lru_cache(maxsize=1)
def _otel_tracer():
    ep = os.getenv("PHOENIX_COLLECTOR_ENDPOINT") or os.getenv("OTEL_EXPORTER_OTLP_ENDPOINT")
    if not ep:
        return None
    try:
        from opentelemetry import trace
        from opentelemetry.exporter.otlp.proto.http.trace_exporter import OTLPSpanExporter
        from opentelemetry.sdk.resources import Resource
        from opentelemetry.sdk.trace import TracerProvider
        from opentelemetry.sdk.trace.export import BatchSpanProcessor
        prov = TracerProvider(resource=Resource.create({"service.name": "gigbid", "openinference.project.name": "gigbid"}))
        prov.add_span_processor(BatchSpanProcessor(OTLPSpanExporter(endpoint=ep.rstrip("/") + "/v1/traces")))
        trace.set_tracer_provider(prov)
        return trace.get_tracer("gigbid")
    except Exception:  # noqa: BLE001 - tracing must never break the app
        return None


def _truncate(v, n=2000):
    s = json.dumps(v, default=str)
    return v if len(s) <= n else s[:n] + "...(truncated)"


def record_span(name: str, kind: str, start: float, end: float, attrs: dict | None = None, status: str = "ok",
                usage: dict | None = None, span_id: str | None = None, parent_id: str | None = None) -> str:
    from common.db import engine, spans
    sid = span_id or uuid.uuid4().hex[:16]
    a = mask_obj({k: _truncate(v) for k, v in (attrs or {}).items()})
    u = usage or {}
    try:
        with engine().begin() as c:
            c.execute(spans.insert().values(
                span_id=sid, trace_id=current_trace.get() or "untraced", parent_id=parent_id or current_span.get(),
                user_id=current_user.get(), thread_id=current_thread.get(), name=name, kind=kind, start=start, end=end,
                status=status, attrs=a, tokens_in=u.get("tokens_in", 0), tokens_out=u.get("tokens_out", 0),
                cost_usd=u.get("cost_usd", 0.0), model=u.get("model")))
    except Exception:  # noqa: BLE001
        pass
    ot = _otel_tracer()
    if ot:
        try:
            s = ot.start_span(name, start_time=int(start * 1e9))
            s.set_attribute("gigbid.trace_id", current_trace.get() or "")
            s.set_attribute("openinference.span.kind", {"llm": "LLM", "tool": "TOOL", "node": "CHAIN"}.get(kind, "CHAIN"))
            for k, v in a.items():
                s.set_attribute(f"gigbid.{k}", v if isinstance(v, (str, int, float, bool)) else json.dumps(v, default=str)[:4000])
            if u:
                s.set_attribute("llm.token_count.prompt", u.get("tokens_in", 0))
                s.set_attribute("llm.token_count.completion", u.get("tokens_out", 0))
                s.set_attribute("llm.model_name", u.get("model") or "")
            s.end(end_time=int(end * 1e9))
        except Exception:  # noqa: BLE001
            pass
    return sid


@contextmanager
def span(name: str, kind: str = "node", **attrs):
    sid = uuid.uuid4().hex[:16]
    parent = current_span.get()
    tok = current_span.set(sid)
    t0 = time.time()
    holder: dict = {"attrs": dict(attrs), "usage": None, "status": "ok"}
    try:
        yield holder
    except Exception as e:
        holder["status"] = "error"
        holder["attrs"]["error"] = f"{type(e).__name__}: {e}"[:500]
        raise
    finally:
        current_span.reset(tok)
        record_span(name, kind, t0, time.time(), holder["attrs"], holder["status"], holder["usage"], sid, parent)


def trace_url(trace_id: str) -> str:
    base = os.getenv("PHOENIX_UI_URL")
    return f"{base.rstrip('/')}/projects/gigbid/traces?traceId={trace_id}" if base else f"/runs/trace/{trace_id}"
