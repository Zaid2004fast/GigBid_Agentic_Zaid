"""LLM-judge calibration (B4): an LLM judge is only trusted after agreeing with a human.

    python -m evals.runners.judge_calibration sample --n 30     # pick 30 proposals -> evals/datasets/judge_items.jsonl
    python -m evals.runners.judge_calibration label             # YOU score each 1-5 (interactive) -> human_labels.jsonl
    python -m evals.runners.judge_calibration judge --model qwen3:1.7b   # LLM scores the same items
    python -m evals.runners.judge_calibration report            # Cohen's kappa (exact + within-1 agreement)

Human labels are never generated by code. The report also lists the items where judge and
human disagree most (viva question 8: "show two and say who was right").
"""
from __future__ import annotations

import argparse
import json
import random
import re
import time

from evals.metrics import cohen_kappa
from evals.runners.harness import ROOT

DS = ROOT / "evals" / "datasets"
OUT = ROOT / "evals" / "results"
ITEMS, HUMAN, JUDGE = DS / "judge_items.jsonl", DS / "human_labels.jsonl", OUT / "judge_scores.json"


def _jsonl(p):
    return [json.loads(x) for x in p.read_text(encoding="utf-8").splitlines() if x.strip()] if p.exists() else []


def sample(n: int) -> None:
    src = json.loads((OUT / "decision_eval.json").read_text())["records"]
    props = [r for r in src if r.get("draft")]
    random.Random(4016).shuffle(props)
    items = [{"id": f"j{i:02d}", "job_id": r["job_id"], "persona": r["persona"], "proposal": r["draft"]} for i, r in enumerate(props[:n])]
    jobs = {json.loads(x)["job"]["id"]: json.loads(x)["job"] for p in ("aiml", "web", "data")
            for x in (DS / f"dev_{p}.jsonl").read_text().splitlines() if x.strip()}
    for it in items:
        j = jobs[it["job_id"]]
        it["job"] = f"{j['title']}\n{j['description'][:900]}"
    ITEMS.write_text("\n".join(json.dumps(i) for i in items), encoding="utf-8")
    print(f"wrote {len(items)} items to {ITEMS}")


def label() -> None:
    done = {x["id"] for x in _jsonl(HUMAN)}
    with HUMAN.open("a", encoding="utf-8") as f:
        for it in _jsonl(ITEMS):
            if it["id"] in done:
                continue
            print("\n" + "=" * 80 + f"\n[{it['id']}] JOB:\n{it['job']}\n\nPROPOSAL:\n{it['proposal']}\n")
            print("Rubric: 5 specific+concrete+answers+right length | 4 one weakness | 3 generic in places | 2 mostly generic | 1 irrelevant/unsafe")
            s = input("score 1-5 (q to stop): ").strip()
            if s == "q":
                break
            f.write(json.dumps({"id": it["id"], "score": int(s), "ts": time.time()}) + "\n")
            f.flush()


def judge(model: str) -> None:
    import asyncio

    from langchain_ollama import ChatOllama

    from agent.llm import load_prompt
    p = load_prompt("judge")

    async def run():
        llm = ChatOllama(model=model, reasoning=False, temperature=0, num_predict=120)
        out = {}
        for it in _jsonl(ITEMS):
            s, u = p.render(job=it["job"], proposal=it["proposal"])
            r = await llm.ainvoke([("system", s), ("user", u + "\nAnswer as: SCORE: <1-5> - <one sentence>")])
            m = re.search(r"SCORE:\s*([1-5])", str(r.content)) or re.search(r"\b([1-5])\b", str(r.content))
            out[it["id"]] = {"score": int(m.group(1)) if m else 3, "raw": str(r.content)[:300]}
            print(it["id"], out[it["id"]]["score"], flush=True)
        return out
    res = asyncio.run(run())
    JUDGE.write_text(json.dumps({"model": model, "prompt_version": p.version, "scores": res}, indent=1))


def report() -> None:
    h = {x["id"]: x["score"] for x in _jsonl(HUMAN)}
    j = json.loads(JUDGE.read_text())["scores"] if JUDGE.exists() else {}
    ids = sorted(set(h) & set(j))
    if len(ids) < 10:
        print(f"only {len(ids)} items have both a human label and a judge score - label more first")
        return
    a, b = [h[i] for i in ids], [j[i]["score"] for i in ids]
    res = {"n": len(ids), "cohen_kappa": round(cohen_kappa(a, b), 4),
           "exact_agreement": round(sum(x == y for x, y in zip(a, b)) / len(ids), 4),
           "within_1": round(sum(abs(x - y) <= 1 for x, y in zip(a, b)) / len(ids), 4),
           "biggest_disagreements": sorted(({"id": i, "human": h[i], "judge": j[i]["score"], "judge_said": j[i]["raw"][:160]} for i in ids),
                                           key=lambda x: -abs(x["human"] - x["judge"]))[:4]}
    (OUT / "judge_calibration.json").write_text(json.dumps(res, indent=1))
    print(json.dumps(res, indent=1))


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("cmd", choices=["sample", "label", "judge", "report"])
    ap.add_argument("--n", type=int, default=30)
    ap.add_argument("--model", default="qwen3:1.7b")
    a = ap.parse_args()
    {"sample": lambda: sample(a.n), "label": label, "judge": lambda: judge(a.model), "report": report}[a.cmd]()
